export function showCard(project) {

  const technologiesHTML = project.technologies.map(technology => {
    return `
      <li class="tech-tag">
        <img src="${technology.src}" alt="${technology.alt}">
      </li>
    `;
  }).join("");

  const featuresHTML = project.features.map(feature => {
    return `
    <li class="des-tag">
    ✓ ${feature}
    </li>
    `
  }).join("");

  const html = `
    <div class="project-card js-project-card" data-category="${project.category}">
    <div class="project-img">
      <img src="${project.image.src}" alt="${project.image.alt}" class="projet-image">
    </div>
    <div class="card-container">
      <div class="card-img">
        <img src="${project.logo.src}"  alt="${project.logo.alt}">
      </div>
      <div class="card-tech">
        <div class="project-content">
          <h3 class="par1">${project.title}</h3>
          <p class="par2">
          ${project.description}
          </p>
        </div>
        <ul class="project-technologies">
        ${technologiesHTML}
      </ul>
      </div>
    </div>
    
      <ul class="project-des">
         ${featuresHTML}
      </ul>

    <div class="project-links">
      <a href="${project.github}" target="_blank" rel="noopener noreferrer" class="btn-github">
        <img src="icons/github.svg" alt="GitHub" class="img-github">
        <span>GitHub</span>
      </a>
      <a href="${project.live}" target="_blank" rel="noopener noreferrer"
        class="btn-live">🌐 Live Demo </a>

    </div>
  </div>
    `;
  return html;
}